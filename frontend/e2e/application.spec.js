import { expect, test } from '@playwright/test';

test('real API: controls, grounded answer, theme and responsive layout', async ({ page }, testInfo) => {
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/');
  await expect(page.getByLabel('Your health question')).toBeVisible();
  await expect(page.getByRole('heading', { name: /Health information/ })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: testInfo.outputPath('landing.png'), fullPage: true });
  await page.getByRole('button', { name: 'Switch to dark mode' }).click();
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark');
  await page.reload();
  await expect(page.getByRole('button', { name: 'Switch to light mode' })).toBeVisible();
  await page.getByRole('button', { name: 'Switch to light mode' }).click();
  await page.getByText('Advanced retrieval settings').click();
  await page.getByLabel('Multilingual strategy').selectOption('direct');
  await expect(page.getByRole('option', { name: 'BM25' })).toHaveAttribute('disabled', '');
  await page.getByLabel('Multilingual strategy').selectOption('translate');
  await page.getByLabel('Retrieval method').selectOption('bm25');
  await expect(page.getByRole('option', { name: 'Direct multilingual retrieval' })).toHaveAttribute('disabled', '');
  await page.getByLabel('Retrieval method').selectOption('semantic');
  await page.getByLabel('Question language').selectOption('te');
  await page.getByRole('button', { name: /మైగ్రేన్/ }).click();
  const requestPromise = page.waitForRequest(request => request.url().endsWith('/api/ask') && request.method() === 'POST');
  await page.getByRole('button', { name: /Ask IndicMed/ }).click();
  const request = await requestPromise;
  expect(request.postDataJSON()).toMatchObject({ language: 'te', retrieval_method: 'semantic', multilingual_strategy: 'translate', top_k: 3 });
  await expect(page.getByText('RETRIEVED ANSWER')).toBeVisible({ timeout: 300000 });
  await expect(page.locator('.answer-card h2')).toContainText('Migraine');
  await expect(page.locator('.answer-text')).toHaveAttribute('lang', 'te');
  await expect(page.locator('.answer-text')).toContainText(/[\u0c00-\u0c7f]/);
  await expect(page.locator('.evidence a')).toHaveAttribute('href', /^https?:\/\//);
  await expect(page.getByText(/does not represent medical accuracy or clinical confidence/)).toBeVisible();
  await expect(page.getByText('RETRIEVAL SIMILARITY SCORE', { exact: true }).first()).toBeVisible();
  expect(await page.locator('.answer-text').evaluate(element => Number.parseFloat(getComputedStyle(element).fontSize))).toBeGreaterThanOrEqual(17);
  expect(await page.getByLabel('Your health question').evaluate(element => Number.parseFloat(getComputedStyle(element).fontSize))).toBeGreaterThanOrEqual(17);
  await page.getByText('Technical details').click();
  await expect(page.locator('.document-id')).toContainText('medquad-');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: testInfo.outputPath('answer.png'), fullPage: true });
  await page.getByRole('button', { name: 'Switch to dark mode' }).click();
  await expect(page.getByLabel('Your health question')).toHaveCSS('background-color', 'rgb(27, 43, 59)');
  await page.screenshot({ path: testInfo.outputPath('dark.png'), fullPage: true });
  await page.getByLabel('Your health question').fill('A changed question');
  await expect(page.getByText('RETRIEVED ANSWER')).toHaveCount(0);
  await page.getByLabel('Question language').selectOption('en');
  await page.getByLabel('Your health question').fill('Who is Allu Arjun?');
  await page.getByRole('button', { name: /Ask IndicMed/ }).click();
  await expect(page.getByText("This question is outside IndicMed's medical scope.")).toBeVisible();
  await expect(page.getByText('RETRIEVED ANSWER')).toHaveCount(0);
  await page.screenshot({ path: testInfo.outputPath('out-of-scope.png'), fullPage: true });
  await page.getByLabel('Question language').selectOption('te');
  await page.getByLabel('Your health question').fill('మైగ్రేన్‌కు కారణాలు ఏమిటి?');
  const comparisonPromise = page.waitForRequest(request => request.url().endsWith('/api/compare') && request.method() === 'POST');
  await page.getByRole('button', { name: 'Compare Strategies' }).click();
  expect((await comparisonPromise).postDataJSON()).toEqual({ query: 'మైగ్రేన్‌కు కారణాలు ఏమిటి?', language: 'te', top_k: 3 });
  await expect(page.getByRole('heading', { name: 'Compare retrieval strategies' })).toBeVisible({ timeout: 300000 });
  await expect(page.getByRole('article', { name: 'Translate-then-Retrieve', exact: true }).locator('.answer-text')).toContainText(/[\u0c00-\u0c7f]/);
  await page.getByText('Rejected candidate · inspection only').click();
  await expect(page.getByRole('article', { name: 'Direct Multilingual Retrieval', exact: true }).getByRole('link')).toHaveAttribute('href', /^https?:\/\//);
  await expect(page.getByRole('article', { name: 'Direct Multilingual Retrieval', exact: true }).locator('.answer-text')).toHaveCount(0);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: testInfo.outputPath('comparison.png'), fullPage: true });
  expect(errors).toEqual([]);
});
